"""Stamp the git version into FW_VERSION at build time (maintenance W4).

Before this, FW_VERSION was a hardcoded "1.0.0" that no bump process
touched — every reflash reported 1.0.0 and the fleet board could not tell
firmware generations apart.

This writes include/fw_version.h (gitignored, regenerated every build)
because passing a quoted string through CPPDEFINES loses its quotes on
some PlatformIO/SCons versions, which turns `c0ffee-dirty` into two
unrelated preprocessor tokens and a wall of compile errors. A generated
header has no quoting layer to survive.

main.cpp picks it up via __has_include and falls back to "dev".

Wired via platformio.ini:  extra_scripts = pre:tools/fwversion.py
"""
Import("env")

import os
import subprocess

root = os.path.dirname(env["PROJECT_DIR"])
try:
    desc = (
        subprocess.run(
            ["git", "describe", "--tags", "--always", "--dirty"],
            capture_output=True,
            text=True,
            cwd=root,
            check=True,
        )
        .stdout.strip()
    )
except Exception:
    desc = "dev"

header = os.path.join(env["PROJECT_DIR"], "include", "fw_version.h")
with open(header, "w") as f:
    f.write('// GENERATED by tools/fwversion.py — do not edit or commit.\n')
    f.write('#define FW_VERSION "%s"\n' % desc)

print("fwversion: FW_VERSION=%s" % desc)
